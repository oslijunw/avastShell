import Foundation

struct AppSettings: Codable, Equatable, Sendable {
    var historyRetentionMonths = 1
    var lastLaunchedAt: Date?
    var lastUpdatedAt: Date?
}

struct ScanHistorySnapshot: Codable, Equatable, Sendable {
    var records: [ScanRecord]
    var lastAutoGeneratedAt: Date?
    var settings = AppSettings()

    private enum CodingKeys: String, CodingKey { case records, lastAutoGeneratedAt, settings }

    init(records: [ScanRecord], lastAutoGeneratedAt: Date?, settings: AppSettings = AppSettings()) {
        self.records = records
        self.lastAutoGeneratedAt = lastAutoGeneratedAt
        self.settings = settings
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        records = try container.decode([ScanRecord].self, forKey: .records)
        lastAutoGeneratedAt = try container.decodeIfPresent(Date.self, forKey: .lastAutoGeneratedAt)
        settings = try container.decodeIfPresent(AppSettings.self, forKey: .settings) ?? AppSettings()
    }
}

struct HistoryStore {
    let fileURL: URL
    var now: () -> Date = Date.init

    static var applicationFileURL: URL {
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("avast.jsonl")
    }

    /// Import older stores once. The originals remain intact.
    func migrateLegacyHistory(from sources: [URL]) throws {
        guard !FileManager.default.fileExists(atPath: fileURL.path) else { return }
        var records: [UUID: ScanRecord] = [:]
        var lastAutomatic: Date?
        var foundHistory = false
        for source in Set(sources) where source != fileURL {
            guard let snapshot = try? HistoryStore(fileURL: source).readSnapshot() else { continue }
            foundHistory = true
            for record in snapshot.records { records[record.id] = record }
            if let date = snapshot.lastAutoGeneratedAt {
                lastAutomatic = max(lastAutomatic ?? date, date)
            }
        }
        if foundHistory {
            try save(ScanHistorySnapshot(records: Array(records.values), lastAutoGeneratedAt: lastAutomatic))
        }
    }

    func load() throws -> ScanHistorySnapshot {
        let timestamp = now()
        var snapshot = try readSnapshot() ?? ScanHistorySnapshot(records: [], lastAutoGeneratedAt: nil)
        if WeeklyScanPolicy.shouldGenerateWeeklyScan(lastGeneratedAt: snapshot.lastAutoGeneratedAt, now: timestamp) {
            let weeklyRecord = ScanFactory.makeWeeklyAutoRecord(now: timestamp)
            snapshot.records.insert(weeklyRecord, at: 0)
            snapshot.lastAutoGeneratedAt = timestamp
        }
        return try save(snapshot)
    }

    @discardableResult
    func save(_ snapshot: ScanHistorySnapshot) throws -> ScanHistorySnapshot {
        let retained = retainingRecentRecords(snapshot)
        try FileManager.default.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        encoder.dateEncodingStrategy = .iso8601
        var lines = [try encoder.encode(Entry(type: .settings, settings: retained.settings, lastAutoGeneratedAt: retained.lastAutoGeneratedAt))]
        for record in retained.records {
            lines.append(try encoder.encode(Entry(type: .scan, record: record)))
        }
        var data = Data()
        for line in lines { data.append(line); data.append(0x0A) }
        try data.write(to: fileURL, options: .atomic)
        return retained
    }

    func deleteRecord(id: UUID) throws -> ScanHistorySnapshot {
        var snapshot = try load()
        snapshot.records.removeAll { $0.id == id }
        return try save(snapshot)
    }

    private func retainingRecentRecords(_ snapshot: ScanHistorySnapshot) -> ScanHistorySnapshot {
        let months = max(1, snapshot.settings.historyRetentionMonths)
        let cutoff = Calendar.current.date(byAdding: .month, value: -months, to: now())!
        var retained = snapshot
        retained.records = snapshot.records.enumerated().filter { $0.element.createdAt >= cutoff }
            .sorted {
                if $0.element.createdAt == $1.element.createdAt { return $0.offset < $1.offset }
                return $0.element.createdAt > $1.element.createdAt
            }.map(\.element)
        return retained
    }

    private func readSnapshot() throws -> ScanHistorySnapshot? {
        guard FileManager.default.fileExists(atPath: fileURL.path) else { return nil }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let data = try Data(contentsOf: fileURL)
        // Compatibility with the previous single JSON object format.
        if let legacy = try? decoder.decode(ScanHistorySnapshot.self, from: data) { return legacy }
        let lines = data.split(separator: 0x0A).filter { !$0.allSatisfy { $0 == 0x20 || $0 == 0x0D || $0 == 0x09 } }
        var snapshot = ScanHistorySnapshot(records: [], lastAutoGeneratedAt: nil)
        var foundSettings = false
        for line in lines {
            let entry = try decoder.decode(Entry.self, from: Data(line))
            switch entry.type {
            case .settings:
                guard !foundSettings, let settings = entry.settings else { throw StoreError.invalidSettings }
                foundSettings = true
                snapshot.settings = settings
                snapshot.lastAutoGeneratedAt = entry.lastAutoGeneratedAt
            case .scan:
                guard let record = entry.record else { throw StoreError.invalidRecord }
                snapshot.records.append(record)
            }
        }
        guard foundSettings else { throw StoreError.invalidSettings }
        return snapshot
    }

    private struct Entry: Codable {
        enum Kind: String, Codable { case settings, scan }
        var type: Kind
        var settings: AppSettings?
        var lastAutoGeneratedAt: Date?
        var record: ScanRecord?
    }
    private enum StoreError: Error { case invalidSettings, invalidRecord }
}
